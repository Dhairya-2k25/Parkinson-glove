import React, { useEffect, useState, useCallback } from 'react';
import {
  Bell, CheckCheck, X, Eye, ShieldCheck, RefreshCw,
  AlertTriangle, Clock, Info,
} from 'lucide-react';
import { alertService, settingsService } from '@/services';
import {
  formatDateTime, timeAgo, alertTypeLabel,
  alertSeverityLabel, alertStatusLabel,
} from '@/utils';
import type { CaregiverAlert, AlertType, AlertStatus } from '@/types';

// ---- Helpers ----

function severityBadgeClass(severity: string) {
  if (severity === 'high') return 'badge-danger';
  if (severity === 'medium') return 'badge-warning';
  return 'badge-neutral';
}

function statusBadgeClass(status: string) {
  if (status === 'new') return 'badge-info';
  if (status === 'resolved') return 'badge-success';
  if (status === 'acknowledged') return 'badge-warning';
  return 'badge-neutral';
}

// ---- Alert Detail Modal ----

interface AlertDetailModalProps {
  alert: CaregiverAlert;
  onClose: () => void;
  onAction: (id: string, action: 'acknowledge' | 'resolve' | 'dismiss') => void;
  actionLoading: string | null;
}

function AlertDetailModal({ alert, onClose, onAction, actionLoading }: AlertDetailModalProps) {
  useEffect(() => {
    const handler = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [onClose]);

  return (
    <div
      className="modal-overlay"
      role="dialog"
      aria-modal="true"
      aria-labelledby="alert-modal-title"
      onClick={e => { if (e.target === e.currentTarget) onClose(); }}
    >
      <div className="modal">
        <div className="modal-header">
          <h3 id="alert-modal-title" className="modal-title">{alert.title}</h3>
          <button className="btn btn-ghost btn-icon" onClick={onClose} aria-label="Close modal">
            <X size={20} />
          </button>
        </div>

        <div className="modal-body space-y-4">
          <div className="flex flex-wrap gap-2">
            <span className={`badge ${severityBadgeClass(alert.severity)}`}>
              {alertSeverityLabel(alert.severity)} Severity
            </span>
            <span className="badge badge-neutral">{alertTypeLabel(alert.type)}</span>
            <span className={`badge ${statusBadgeClass(alert.status)}`}>
              {alertStatusLabel(alert.status)}
            </span>
            {!alert.isConfirmed && (
              <span className="badge badge-warning">Possible Event (Unconfirmed)</span>
            )}
          </div>

          <p className="text-sm text-text-secondary leading-relaxed">{alert.description}</p>

          <div className="grid grid-cols-2 gap-3">
            <ModalRow label="Generated" value={formatDateTime(alert.timestamp)} />
            <ModalRow label="Alert ID" value={alert.id} />
            {alert.sessionId && <ModalRow label="Session" value={alert.sessionId} />}
            {alert.acknowledgedAt && (
              <ModalRow label="Acknowledged" value={formatDateTime(alert.acknowledgedAt)} />
            )}
            {alert.acknowledgedBy && (
              <ModalRow label="Acknowledged By" value={alert.acknowledgedBy} />
            )}
            {alert.resolvedAt && (
              <ModalRow label="Resolved" value={formatDateTime(alert.resolvedAt)} />
            )}
          </div>

          <div className="p-3 rounded-lg bg-surface-tertiary">
            <p className="text-xs text-text-tertiary leading-relaxed">
              <strong>Important:</strong> This alert is an observational notification generated by
              the NeuroGlove system. It does not constitute a medical diagnosis or clinical
              assessment. Consult a qualified healthcare professional for any medical concerns.
            </p>
          </div>
        </div>

        <div className="modal-footer">
          <button className="btn btn-secondary" onClick={onClose}>
            Close
          </button>
          {alert.status === 'new' && (
            <button
              className="btn btn-teal"
              onClick={() => onAction(alert.id, 'acknowledge')}
              disabled={actionLoading === alert.id + 'acknowledge'}
            >
              <CheckCheck size={16} />
              {actionLoading === alert.id + 'acknowledge' ? 'Acknowledging…' : 'Acknowledge'}
            </button>
          )}
          {(alert.status === 'new' || alert.status === 'acknowledged') && (
            <button
              className="btn btn-secondary"
              onClick={() => onAction(alert.id, 'resolve')}
              disabled={actionLoading === alert.id + 'resolve'}
            >
              <ShieldCheck size={16} />
              {actionLoading === alert.id + 'resolve' ? 'Resolving…' : 'Mark Resolved'}
            </button>
          )}
        </div>
      </div>
    </div>
  );
}

function ModalRow({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <p className="text-xs font-medium text-text-secondary mb-0.5">{label}</p>
      <p className="text-sm text-text-primary">{value}</p>
    </div>
  );
}

// ---- Main Page ----

const AlertsPage: React.FC = () => {
  const [alerts, setAlerts] = useState<CaregiverAlert[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [statusFilter, setStatusFilter] = useState<AlertStatus | 'all'>('all');
  const [typeFilter, setTypeFilter] = useState<AlertType | 'all'>('all');
  const [selectedAlert, setSelectedAlert] = useState<CaregiverAlert | null>(null);
  const [actionLoading, setActionLoading] = useState<string | null>(null);
  const settings = settingsService.getSettings();

  const fetchAlerts = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const data = await alertService.getAlerts('demo-patient-001', {
        status: statusFilter,
        type: typeFilter,
      });
      setAlerts(data);
    } catch {
      setError('Unable to load alerts.');
    } finally {
      setLoading(false);
    }
  }, [statusFilter, typeFilter]);

  useEffect(() => {
    fetchAlerts();
  }, [fetchAlerts]);

  const handleAction = useCallback(
    async (id: string, action: 'acknowledge' | 'resolve' | 'dismiss') => {
      setActionLoading(id + action);
      setError(null);
      try {
        let updated: CaregiverAlert | null = null;
        if (action === 'acknowledge') updated = await alertService.acknowledgeAlert(id);
        else if (action === 'resolve') updated = await alertService.resolveAlert(id);
        else if (action === 'dismiss') updated = await alertService.dismissAlert(id);

        if (updated) {
          setAlerts(prev => prev.map(a => (a.id === id ? updated! : a)));
          if (selectedAlert?.id === id) setSelectedAlert(updated);
        }
      } catch {
        setError('Action failed. Please try again.');
      } finally {
        setActionLoading(null);
      }
    },
    [selectedAlert]
  );

  const unreadCount = alerts.filter(a => a.status === 'new').length;

  return (
    <div>
      {settings.dataMode === 'demo' && (
        <div className="demo-banner" role="status">
          <Info size={16} aria-hidden="true" />
          <span>
            <strong>Demonstration Mode</strong> — Alerts shown are simulated demonstration data.
          </span>
        </div>
      )}

      {/* Unread banner */}
      {!loading && unreadCount > 0 && (
        <div
          className="flex items-center gap-2 mb-4 px-4 py-3 rounded-lg bg-warning-50 border border-warning-200"
          role="status"
          aria-live="polite"
        >
          <Bell size={16} className="text-warning-600 shrink-0" />
          <span className="text-sm font-medium text-warning-700">
            {unreadCount} unreviewed alert{unreadCount !== 1 ? 's' : ''} — please review and acknowledge
          </span>
        </div>
      )}

      {/* Filters */}
      <div className="card mb-6">
        <div className="card-body">
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 items-end">
            <div>
              <label htmlFor="alert-status-filter" className="form-label">Status</label>
              <select
                id="alert-status-filter"
                className="form-input form-select"
                value={statusFilter}
                onChange={e => setStatusFilter(e.target.value as AlertStatus | 'all')}
              >
                <option value="all">All Statuses</option>
                <option value="new">New</option>
                <option value="acknowledged">Acknowledged</option>
                <option value="resolved">Resolved</option>
                <option value="dismissed">Dismissed</option>
              </select>
            </div>
            <div>
              <label htmlFor="alert-type-filter" className="form-label">Type</label>
              <select
                id="alert-type-filter"
                className="form-input form-select"
                value={typeFilter}
                onChange={e => setTypeFilter(e.target.value as AlertType | 'all')}
              >
                <option value="all">All Types</option>
                <option value="failed_grasp">Failed Grasp</option>
                <option value="tremor_spike">Tremor Spike</option>
                <option value="device_disconnected">Device Disconnected</option>
                <option value="missed_session">Missed Session</option>
              </select>
            </div>
            <div className="flex items-end gap-2">
              <button
                className="btn btn-secondary flex-1"
                onClick={fetchAlerts}
                disabled={loading}
                aria-label="Refresh alerts list"
              >
                <RefreshCw size={14} className={loading ? 'animate-spin' : ''} />
                Refresh
              </button>
              <span className="text-sm text-text-tertiary whitespace-nowrap self-center">
                {alerts.length} alert{alerts.length !== 1 ? 's' : ''}
              </span>
            </div>
          </div>
        </div>
      </div>

      {/* Error */}
      {error && (
        <div
          className="mb-4 px-4 py-3 rounded-lg bg-danger-50 border border-danger-100 text-danger-700 text-sm flex items-center gap-2"
          role="alert"
        >
          <AlertTriangle size={14} className="shrink-0" />
          {error}
        </div>
      )}

      {/* Content */}
      {loading ? (
        <div className="space-y-3">
          {[1, 2, 3].map(i => (
            <div key={i} className="card">
              <div className="card-body">
                <div className="skeleton h-20 w-full" />
              </div>
            </div>
          ))}
        </div>
      ) : alerts.length === 0 ? (
        <div className="card">
          <div className="card-body">
            <div className="empty-state">
              <ShieldCheck className="empty-state-icon text-success-500 mx-auto" />
              <p className="empty-state-title">No alerts found</p>
              <p className="empty-state-description">
                {statusFilter !== 'all' || typeFilter !== 'all'
                  ? 'No alerts match the selected filters. Try changing filter criteria.'
                  : 'No caregiver alerts have been generated. This is a good sign.'}
              </p>
            </div>
          </div>
        </div>
      ) : (
        <div className="space-y-3" role="list" aria-label="Caregiver alerts">
          {alerts.map(alert => (
            <div
              key={alert.id}
              role="listitem"
              className={`card transition-all ${
                alert.status === 'new'
                  ? 'border-l-4 border-l-warning-400'
                  : alert.status === 'resolved'
                  ? 'opacity-75'
                  : ''
              }`}
            >
              <div className="card-body">
                <div className="flex flex-col sm:flex-row sm:items-start gap-4">
                  {/* Severity stripe */}
                  <div
                    className={`w-2 h-2 mt-1.5 rounded-full shrink-0 ${
                      alert.severity === 'high'
                        ? 'bg-danger-500'
                        : alert.severity === 'medium'
                        ? 'bg-warning-500'
                        : 'bg-navy-300'
                    }`}
                    aria-hidden="true"
                  />

                  {/* Main content */}
                  <div className="flex-1 min-w-0">
                    <div className="flex flex-wrap items-center gap-2 mb-1">
                      <span className={`badge ${severityBadgeClass(alert.severity)}`}>
                        {alertSeverityLabel(alert.severity)}
                      </span>
                      <span className="badge badge-neutral">{alertTypeLabel(alert.type)}</span>
                      <span className={`badge ${statusBadgeClass(alert.status)}`}>
                        {alertStatusLabel(alert.status)}
                      </span>
                      {!alert.isConfirmed && (
                        <span className="badge badge-warning text-xs">Possible Event</span>
                      )}
                    </div>

                    <h4 className="font-semibold text-text-primary">{alert.title}</h4>
                    <p className="text-sm text-text-secondary mt-0.5 leading-relaxed">
                      {alert.description}
                    </p>

                    <div className="flex flex-wrap items-center gap-3 mt-2 text-xs text-text-tertiary">
                      <span className="flex items-center gap-1">
                        <Clock size={11} aria-hidden="true" />
                        {timeAgo(alert.timestamp)}
                      </span>
                      <span>{formatDateTime(alert.timestamp)}</span>
                      {alert.acknowledgedAt && (
                        <span>Acknowledged {timeAgo(alert.acknowledgedAt)}</span>
                      )}
                    </div>
                  </div>

                  {/* Action buttons */}
                  <div className="flex flex-wrap gap-2 shrink-0">
                    <button
                      className="btn btn-sm btn-secondary"
                      onClick={() => setSelectedAlert(alert)}
                      aria-label={`View full details for: ${alert.title}`}
                    >
                      <Eye size={14} />
                      Details
                    </button>

                    {alert.status === 'new' && (
                      <button
                        className="btn btn-sm btn-teal"
                        onClick={() => handleAction(alert.id, 'acknowledge')}
                        disabled={!!actionLoading}
                        aria-label={`Acknowledge alert: ${alert.title}`}
                      >
                        <CheckCheck size={14} />
                        {actionLoading === alert.id + 'acknowledge' ? '…' : 'Acknowledge'}
                      </button>
                    )}

                    {(alert.status === 'new' || alert.status === 'acknowledged') && (
                      <button
                        className="btn btn-sm btn-secondary"
                        onClick={() => handleAction(alert.id, 'resolve')}
                        disabled={!!actionLoading}
                        aria-label={`Resolve alert: ${alert.title}`}
                      >
                        <ShieldCheck size={14} />
                        {actionLoading === alert.id + 'resolve' ? '…' : 'Resolve'}
                      </button>
                    )}

                    {alert.status !== 'dismissed' && alert.status !== 'resolved' && (
                      <button
                        className="btn btn-sm btn-ghost text-text-tertiary hover:text-danger-600"
                        onClick={() => handleAction(alert.id, 'dismiss')}
                        disabled={!!actionLoading}
                        aria-label={`Dismiss alert: ${alert.title}`}
                      >
                        <X size={14} />
                        {actionLoading === alert.id + 'dismiss' ? '…' : 'Dismiss'}
                      </button>
                    )}
                  </div>
                </div>
              </div>
            </div>
          ))}
        </div>
      )}

      {/* Detail Modal */}
      {selectedAlert && (
        <AlertDetailModal
          alert={selectedAlert}
          onClose={() => setSelectedAlert(null)}
          onAction={handleAction}
          actionLoading={actionLoading}
        />
      )}
    </div>
  );
};

export default AlertsPage;
